#Requires -Version 7

<#
.SYNOPSIS
    Creates Microsoft Entra ID workforce app registrations for this sample.

.DESCRIPTION
    Creates a single-tenant web/API application and a public MAUI application,
    grants the MAUI app delegated access to the sample API, and updates only
    this copied sample's placeholder configuration files.
#>

[CmdletBinding()]
param(
    [string] $TenantId,
    [string] $MauiAppName = "workforce-dotnet-blazor-maui",
    [string] $WebAppName = "workforce-dotnet-blazor-maui-web",
    [ValidateSet("Global", "AzureChinaCloud", "AzureUSGovernment")]
    [string] $AzureEnvironmentName = "Global"
)

$ErrorActionPreference = "Stop"
$ProjectDir = Resolve-Path (Join-Path $PSScriptRoot "..")

foreach ($module in @("Microsoft.Graph.Applications", "Microsoft.Graph.Identity.DirectoryManagement")) {
    if (-not (Get-Module -ListAvailable -Name $module)) {
        Install-Module $module -Scope CurrentUser -Force
    }

    Import-Module $module
}

Connect-MgGraph `
    -TenantId $TenantId `
    -Scopes "Application.ReadWrite.All", "Organization.Read.All" `
    -Environment $AzureEnvironmentName `
    -NoWelcome

try {
    $context = Get-MgContext
    $tenantId = $context.TenantId
    $tenantDomain = (Get-MgOrganization).VerifiedDomains |
        Where-Object IsDefault |
        Select-Object -ExpandProperty Name
    $authorityHost = switch ($AzureEnvironmentName) {
        "AzureChinaCloud" { "https://login.chinacloudapi.cn/" }
        "AzureUSGovernment" { "https://login.microsoftonline.us/" }
        default { "https://login.microsoftonline.com/" }
    }

    function New-OrReuseApp {
        param(
            [string] $Name,
            [hashtable[]] $RequiredResourceAccess = @(),
            [switch] $PublicClient
        )

        $existing = Get-MgApplication -Filter "displayName eq '$Name'" -Top 1
        if ($existing) {
            Write-Host "Using existing app registration '$Name' ($($existing.AppId))."
            return $existing
        }

        $parameters = @{
            DisplayName = $Name
            SignInAudience = "AzureADMyOrg"
            RequiredResourceAccess = $RequiredResourceAccess
        }
        if ($PublicClient) {
            $parameters.IsFallbackPublicClient = $true
        }

        $app = New-MgApplication @parameters
        New-MgServicePrincipal -AppId $app.AppId | Out-Null
        Write-Host "Created app registration '$Name' ($($app.AppId))."
        return $app
    }

    $webApp = New-OrReuseApp -Name $WebAppName
    $webAppId = $webApp.AppId
    $apiScopeId = [Guid]::NewGuid().ToString()
    $mauiApp = New-OrReuseApp -Name $MauiAppName -PublicClient

    Update-MgApplication -ApplicationId $webApp.Id `
        -IdentifierUris @("api://$webAppId") `
        -Web @{ RedirectUris = @("https://localhost:7157/signin-oidc") } `
        -Api @{
            Oauth2PermissionScopes = @(
                @{
                    Id = $apiScopeId
                    AdminConsentDisplayName = "Access the sample API"
                    AdminConsentDescription = "Allow the MAUI app to access the sample API on behalf of the signed-in user."
                    Value = "access_as_user"
                    Type = "User"
                    IsEnabled = $true
                }
            )
            PreAuthorizedApplications = @(
                @{
                    AppId = $mauiApp.AppId
                    DelegatedPermissionIds = @($apiScopeId)
                }
            )
        }

    $secret = Add-MgApplicationPassword -ApplicationId $webApp.Id -PasswordCredential @{
        DisplayName = "Auto-generated by Configure.ps1"
    }

    $apiPermission = @{
        ResourceAppId = $webAppId
        ResourceAccess = @(@{ Id = $apiScopeId; Type = "Scope" })
    }
    Update-MgApplication -ApplicationId $mauiApp.Id `
        -RequiredResourceAccess @($apiPermission) `
        -PublicClient @{
            RedirectUris = @("msal$($mauiApp.AppId)://auth", "http://localhost")
    }

    $mauiSettingsPath = Join-Path $ProjectDir "SignInBlazorMauiWorkforce" "appsettings.json"
    $mauiSettings = Get-Content $mauiSettingsPath -Raw | ConvertFrom-Json
    $mauiSettings.AzureAd.Authority = "$authorityHost$tenantId"
    $mauiSettings.AzureAd.ClientId = $mauiApp.AppId
    $mauiSettings.DownstreamApi.Scopes = @("api://$webAppId/access_as_user")
    $mauiSettings | ConvertTo-Json -Depth 10 | Set-Content $mauiSettingsPath -Encoding UTF8

    $webSettingsPath = Join-Path $ProjectDir "SignInBlazorMauiWorkforce.Web" "appsettings.json"
    $webSettings = Get-Content $webSettingsPath -Raw | ConvertFrom-Json
    $webSettings.AzureAd.Instance = $authorityHost
    $webSettings.AzureAd.TenantId = $tenantId
    $webSettings.AzureAd.ClientId = $webAppId
    $webSettings.AzureAd.ClientSecret = $secret.SecretText
    $webSettings | ConvertTo-Json -Depth 10 | Set-Content $webSettingsPath -Encoding UTF8

    foreach ($platformFile in @(
        (Join-Path $ProjectDir "SignInBlazorMauiWorkforce" "Platforms" "Android" "AndroidManifest.xml"),
        (Join-Path $ProjectDir "SignInBlazorMauiWorkforce" "Platforms" "iOS" "Info.plist"),
        (Join-Path $ProjectDir "SignInBlazorMauiWorkforce" "Platforms" "MacCatalyst" "Info.plist")
    )) {
        (Get-Content $platformFile -Raw) `
            -replace "msalEnter_the_Application_Id_Here", "msal$($mauiApp.AppId)" |
            Set-Content $platformFile -Encoding UTF8
    }

    Write-Host "Configured workforce tenant $tenantDomain ($tenantId)." -ForegroundColor Green
    Write-Host "MAUI app: $($mauiApp.AppId)"
    Write-Host "Web app:  $webAppId"
    Write-Host "API scope: api://$webAppId/access_as_user"
}
finally {
    Disconnect-MgGraph | Out-Null
}
